using JuliaSynth.Runtime;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Numerics;
using System.Text;

namespace JuliaSynth.Model
{
    /// <summary>
    /// A design as one Julia script, the variable holding each node's value, and the packages it loads.
    /// </summary>
    public sealed record JuliaScript(string Text, IReadOnlyDictionary<string, string> Variables, IReadOnlyList<string> Packages)
    {
        /// <summary>
        /// Whether it runs as a stream (the design watches a folder): until stopped, rather than once.
        /// </summary>
        public bool Streams { get; init; }

        /// <summary>
        /// The watched folder a stream goes through, when it <see cref="Streams"/>.
        /// </summary>
        public WatchNode? Watched { get; init; }

        /// <summary>
        /// The ids of the nodes whose values change from file to file, when the design goes through files one
        /// at a time (watched, or a Files node so set): worked out again for each, or taking a next value. Empty otherwise.
        /// </summary>
        public IReadOnlySet<string> Looped { get; init; } = new HashSet<string>();
    }

    /// <summary>
    /// Turns a design into a Julia script: the packages it needs, the function definitions, then every
    /// node's value in wiring order, each in a variable (x1, v1, f_out, ...).
    /// </summary>
    /// <remarks>
    /// A script for running is instrumented: it reports every value (see <see cref="Reports"/>), and a
    /// failure only stops the values depending on it. An exported script is plain Julia.
    /// </remarks>
    public static class ScriptGenerator
    {
        private const string Indent = "    ";

        /// <param name="plotFolder">Where plots write their numbers for the app to read; JuliaSynth's temporary folder by default.</param>
        /// <param name="stopFile">For a run of a stream: the file whose appearing ends it.</param>
        public static JuliaScript Generate(IEnumerable<Node> designNodes, IEnumerable<Connection> designConnections, bool instrumented, string? plotFolder = null, string? stopFile = null)
        {
            plotFolder ??= Path.Combine(Path.GetTempPath(), "JuliaSynth");
            List<Node> nodes = designNodes.ToList();
            List<Connection> attached = designConnections.Where(c => Wiring.IsAttached(nodes, c)).ToList();

            // Builders write wired arguments by name and typed-in ones by value; make sure they know which is
            // which for these connections (the designer keeps this up to date, a design built elsewhere may not).
            HashSet<string> wired = attached.Select(c => c.ParameterID).ToHashSet();
            foreach (Parameter parameter in nodes.SelectMany(n => n.Ports))
            {
                parameter.IsWired = wired.Contains(parameter.ID);
            }

            // Wires into next ports carry a value on to the next file: nothing waits for them.
            List<Connection> nextWires = attached.Where(c => Wiring.IsNextWire(nodes, c)).ToList();
            List<Connection> connections = attached.Except(nextWires).ToList();

            Dictionary<string, string> variables = NameVariables(nodes);
            List<Node> order = WiringOrder(nodes, connections);

            StringBuilder script = new();
            _ = script.AppendLine("# Generated by JuliaSynth.");
            if (instrumented)
            {
                _ = script.AppendLine().AppendLine(Reports.Prelude.TrimEnd());
                if (nodes.OfType<PlotNode>().Any())
                {
                    _ = script.AppendLine(PlotData.Prelude.TrimEnd());
                }
            }

            // Files go through Map; a script without them is still valid Julia, so these are in an exported one too.
            if (nodes.Any(n => n is FilesNode or MapNode))
            {
                _ = script.AppendLine().AppendLine(FilesNode.Prelude.TrimEnd());
            }

            if (instrumented && nodes.OfType<MapNode>().Any())
            {
                _ = script.AppendLine(MapNode.Prelude.TrimEnd());
            }
            else if (nodes.OfType<MapNode>().Any(m => m.InParallel))
            {
                _ = script.AppendLine(MapNode.ParallelPrelude.TrimEnd());
            }

            // Watching a folder is plain Julia too; showing how far a loop through files got is for runs.
            if (nodes.OfType<WatchNode>().Any())
            {
                _ = script.AppendLine().AppendLine(WatchNode.Prelude.TrimEnd());
            }

            if (instrumented && nodes.OfType<FilesNode>().Any(f => f.EachFile))
            {
                _ = script.AppendLine(WatchNode.RunPrelude.TrimEnd());
            }

            if (nodes.OfType<WindowNode>().Any())
            {
                _ = script.AppendLine().AppendLine(WindowNode.Prelude.TrimEnd());
            }

            if (nodes.Any(n => n is ArrayFile file ? FileFormats.IsDelimited(file.Format) : n is FilesNode files && FileFormats.IsDelimited(files.Format)))
            {
                _ = script.AppendLine().AppendLine(FileFormats.Prelude.TrimEnd());
            }

            // Functions wired into a Map are applied by it: one whose parameter isn't wired has no value of its own.
            Dictionary<string, Node> byID = nodes.ToDictionary(n => n.ID);
            HashSet<string> applied = connections
                .Where(c => byID[c.TargetID].Inputs.Any(p => p.ID == c.ParameterID && p.IsFunctionPort))
                .Select(c => c.SourceID)
                .ToHashSet();

            // Functions bring their packages into scope themselves (their code starts with its using
            // statements); the rest come from here. A run checks them all first.
            List<string> usings = order.SelectMany(PackagesOf).Distinct().Order(StringComparer.Ordinal).ToList();
            List<string> packages = order.SelectMany(NeededPackages).Distinct().Order(StringComparer.Ordinal).ToList();
            if (instrumented && packages.Count > 0)
            {
                _ = script.AppendLine().Append(LoadPackages(usings, packages.Except(usings)));
            }
            else
            {
                List<string> imports = order.SelectMany(ImportsOf).Distinct().Order(StringComparer.Ordinal).Except(usings).ToList();
                if (usings.Count + imports.Count > 0)
                {
                    _ = script.AppendLine();
                }

                if (usings.Count > 0)
                {
                    _ = script.AppendLine($"using {string.Join(", ", usings)}");
                }

                if (imports.Count > 0)
                {
                    _ = script.AppendLine($"import {string.Join(", ", imports)}");
                }
            }

            List<Function> functions = order.OfType<Function>().Where(f => f.Error is null).ToList();
            if (functions.Count > 0)
            {
                // Each definition is evaluated on its own, so a syntax error in one body only fails that function.
                _ = script.AppendLine().AppendLine("# Functions");
                _ = instrumented
                    ? script.AppendJoin(string.Empty, functions.Select(Definition))
                    : script.AppendJoin("\n\n", functions.Select(f => f.Code)).AppendLine();
            }


            // A design going through files one at a time, as they are written to a watched folder (a stream,
            // until stopped) or those of a folder: the nodes after the files again for each, and after the inputs
            // taking a next value; the others once, before. Folders zipped come first, then a watched folder; one
            // loop a design. Zipped, the loop goes through a watched one's files (else the first one's), and the
            // others' files of the same names go with them.
            ZipNode? zip = order.OfType<ZipNode>().FirstOrDefault(z => ZipStreams(z, connections, byID).Problem is null);
            List<FilesNode> zipped = zip is null ? [] : ZipStreams(zip, connections, byID).Streams;
            FilesNode? root = zipped.OfType<WatchNode>().FirstOrDefault() ?? zipped.FirstOrDefault()
                ?? order.OfType<WatchNode>().FirstOrDefault(w => w.Error is null)
                ?? order.OfType<FilesNode>().FirstOrDefault(f => f.EachFile && f.Error is null);
            List<FilesNode> twins = zipped.Where(f => f != root).Distinct().ToList();
            List<Node> carried = root is null ? [] : nextWires.Select(c => byID[c.TargetID]).Distinct().ToList();
            HashSet<string> looped = root is null ? [] : Downstream(root, connections, byID);
            foreach (FilesNode twin in twins)
            {
                looped.UnionWith(Downstream(twin, connections, byID));
            }

            foreach (Node input in carried)
            {
                looped.UnionWith(Downstream(input, connections, byID));
            }

            // The name of the file the loop is at changes from file to file too.
            foreach (FileNameNode name in nodes.OfType<FileNameNode>().Where(_ => root is not null))
            {
                looped.UnionWith(Downstream(name, connections, byID));
            }

            // An input with a next value starts with its own, worked out once, before the loop.
            looped.ExceptWith(carried.Select(c => c.ID));

            // The nodes after an Only when node, held back while its condition is false: those it holds back.
            Dictionary<string, List<WhenNode>> gates = [];
            foreach (WhenNode when in order.OfType<WhenNode>())
            {
                foreach (string id in Downstream(when, connections, byID).Where(id => id != when.ID))
                {
                    (gates.TryGetValue(id, out List<WhenNode>? list) ? list : gates[id] = []).Add(when);
                }
            }

            LoopContext? loop = root is null ? null : new(root, twins, zip, looped);

            if (order.Count > 0)
            {
                _ = script.AppendLine().AppendLine("# Values");
            }

            // What keeps from value to value: the values a Window keeps, and files of rows started anew.
            foreach (Node node in order)
            {
                if (node is WindowNode)
                {
                    _ = script.AppendLine($"{variables[node.ID]}_values = []");
                }
                else if (node is SaveFile { SavesPerFile: true, Problem: null } rows)
                {
                    _ = script.AppendLine(rows.StartPerFile);
                }
            }

            foreach (Node node in order.Where(n => !looped.Contains(n.ID)))
            {
                _ = script.Append(NodeCode(node));
            }

            if (root is not null)
            {
                string body = string.Concat(order.Where(n => looped.Contains(n.ID)).Select(NodeCode)) + Reassignments();
                string frame = variables[root.ID];
                List<string> inStep = twins.Select(t => t.Folder).ToList();
                string files = inStep.Count > 0 ? $"_jsynth_in_step({root.Julia}, {FilesNode.FoldersJulia(inStep)})" : root.Julia;
                string start = root is WatchNode watched
                    ? $"{watched.Watch(instrumented ? stopFile : null, inStep)} do _path, _n, _show"
                    : instrumented
                        ? $"_jsynth_each({StringLiteral(root.ID)}, () -> {files}) do _path, _n, _show"
                        : $"for _path in {files}.paths";
                string what = root is WatchNode
                    ? $"again for every file written to the folder, {(instrumented ? "until stopped" : "until stopped (Ctrl+C)")}"
                    : "again for each file of the folder, in name order";
                if (inStep.Count > 0)
                {
                    what += $", with the files of the same name in {string.Join(", ", twins.Select(t => variables[t.ID]))}";
                }
                _ = script.AppendLine().AppendLine($"# The loop: the values from {frame} on, {what}");
                if (instrumented)
                {
                    _ = script.AppendLine("const _jsynth_before_loop = copy(_jsynth_failed)")
                        .AppendLine("const _jsynth_held_before_loop = copy(_jsynth_held)")
                        .AppendLine(start)
                        .AppendLine($"{Indent}_jsynth_frame_start(_show, _jsynth_before_loop, _jsynth_held_before_loop)")
                        .Append(Indented(body))
                        .AppendLine("end")
                        .AppendLine("_jsynth_quiet[] = false");
                }
                else
                {
                    _ = script.AppendLine(start).Append(Indented(body)).AppendLine("end");
                }
            }
            else if (nextWires.Count > 0)
            {
                // Without files to go through one at a time, there is no next file to take a value for.
                _ = script.AppendLine().AppendLine(string.Join("\n", nextWires.Select(c =>
                    $"# {variables[c.TargetID]} keeps its value: it takes {variables[c.SourceID]} for the next file only when files are gone through one at a time.")));
            }

            // After each file, the inputs with a next value take it, all together: the values they get are
            // those of this file. In a run, an input whose next value failed keeps the one it has.
            string Reassignments()
            {
                if (nextWires.Count == 0)
                {
                    return string.Empty;
                }

                // An input taking another's value takes the one it had for this file: through a temporary.
                bool chained = nextWires.Any(w => carried.Any(c => c.ID == w.SourceID));
                StringBuilder code = new("# The inputs take their next values, for the next file\n");
                List<(Connection Wire, string Value)> values = [];
                for (int i = 0; i < nextWires.Count; i++)
                {
                    Connection wire = nextWires[i];
                    string next = variables[wire.SourceID];
                    if (chained)
                    {
                        string input = variables[wire.TargetID];
                        _ = code.AppendLine(instrumented
                            ? $"_next{i + 1} = _jsynth_blocked({StringLiteral(wire.SourceID)}) ? {input} : {next}"
                            : GateOf(wire.SourceID) is string held ? $"_next{i + 1} = {held} ? {next} : {input}"
                            : $"_next{i + 1} = {next}");
                        next = $"_next{i + 1}";
                    }

                    values.Add((wire, next));
                }

                foreach ((Connection wire, string next) in values)
                {
                    string input = variables[wire.TargetID];
                    _ = !instrumented ? code.Append(Gated(GateOf(wire.SourceID), $"global {input} = {next}"))
                        : chained ? code.AppendLine($"global {input} = {next}").AppendLine($"_jsynth_ok({StringLiteral(wire.TargetID)}, {input})")
                        : code.AppendLine($"_jsynth_blocked({StringLiteral(wire.SourceID)}) || (global {input} = {next})").AppendLine($"_jsynth_ok({StringLiteral(wire.TargetID)}, {input})");
                }

                return code.ToString();
            }

            // In a plain script, whether the Only when nodes before a node let its value through: passed1_ok && ...
            string? GateOf(string id, bool self = true)
            {
                IEnumerable<WhenNode> whens = gates.TryGetValue(id, out List<WhenNode>? before) ? before : [];
                if (self && byID[id] is WhenNode when)
                {
                    whens = whens.Append(when);
                }

                List<string> flags = whens.Select(w => $"{variables[w.ID]}_ok").ToList();
                return flags.Count == 0 ? null : string.Join(" && ", flags);
            }

            static string Gated(string? gate, string code)
            {
                code = code.EndsWith('\n') ? code : code + "\n";
                return gate is null ? code : $"if {gate}\n{Indented(code)}end\n";
            }

            // One node's value: computed (and reported, in a run), or why it isn't.
            string NodeCode(Node node)
            {
                List<Connection> inputs = connections.Where(c => c.TargetID == node.ID).ToList();
                if (node is Function used && applied.Contains(used.ID) && used.Parameters.Any(p => inputs.All(c => c.ParameterID != p.ID)))
                {
                    return string.Empty;
                }

                string variable = variables[node.ID];
                bool inStream = looped.Contains(node.ID);
                (string? expression, string? problem) = Expression(node, inputs, variables, byID, instrumented, plotFolder, inStream ? loop : null);

                // Values of a loop are assigned in a function (the one called for each file) or a loop: globals, by name.
                string assign = inStream ? $"global {variable}" : variable;
                // An Only when node's condition, which says whether its value passes.
                string? condition = node is WhenNode gate && inputs.FirstOrDefault(c => c.ParameterID == gate.Condition.ID) is Connection test
                    ? variables[test.SourceID]
                    : null;

                if (!instrumented)
                {
                    // Showing or saving a value is something to do, not a value to keep; plots are drawn by
                    // JuliaSynth, so a plain script only says how to draw them in Julia. A node after an Only when
                    // node is worked out only when its condition held.
                    string line = problem is not null ? $"# {variable}: {problem}"
                        : node is SaveFile { SavesPerFile: true } rows ? rows.PerFileStatement(variables[inputs[0].SourceID], named: inStream)
                        : node is OutputNode output ? output.Statement(variables[inputs[0].SourceID])
                        : node is PlotNode plot ? PlotHint(plot, inputs, variables)
                        : node is WhenNode ? $"{(inStream ? "global " : string.Empty)}{variable}_ok = {condition}\nif {variable}_ok\n{Indent}{assign} = {expression}\nend"
                        : $"{assign} = {expression}";
                    return problem is not null ? line + "\n" : Gated(GateOf(node.ID, self: false), line);
                }

                StringBuilder code = new($"# {variable}\n");
                if (problem is not null)
                {
                    return code.AppendLine($"_jsynth_skip({StringLiteral(node.ID)}, {StringLiteral(problem)})").ToString();
                }

                string id = StringLiteral(node.ID);
                string[] blockers = inputs.Select(c => StringLiteral(c.SourceID)).Distinct().ToArray();
                string[] needed = NeededPackages(node).Select(StringLiteral).ToArray();
                List<(string Condition, string Then)> conditions = [];

                // A plot of a loop is drawn for the files whose values are shown, not for every one.
                if (inStream && node is PlotNode)
                {
                    conditions.Add(("_jsynth_quiet[]", "nothing"));
                }

                // A function whose definition failed has nothing to call; its error is already reported.
                if (node is Function)
                {
                    conditions.Add(($"_jsynth_blocked({id})", "nothing"));
                }

                // Held back, it shows the value it keeps: on a file whose values are shown, the one it got may not have
                // been (a plot keeps showing its last drawing).
                string kept = node is PlotNode ? "nothing" : $"@isdefined({variable}) && _jsynth_ok({id}, {variable})";

                // Held back by a false condition before it: going through files, it keeps the value it had.
                string[] holders = inputs.Where(c => byID[c.SourceID] is WhenNode || gates.ContainsKey(c.SourceID))
                    .Select(c => StringLiteral(c.SourceID))
                    .Distinct()
                    .ToArray();
                if (holders.Length > 0)
                {
                    conditions.Add(($"_jsynth_held_by({string.Join(", ", holders)})", inStream
                        ? $"(_jsynth_hold({id}); {kept})"
                        : $"(_jsynth_hold({id}); _jsynth_skip({id}, \"A condition before it is false: nothing passed.\"))"));
                }

                if (blockers.Length > 0)
                {
                    conditions.Add(($"_jsynth_blocked({string.Join(", ", blockers)})", $"_jsynth_skip({id}, \"An input failed.\")"));
                }

                if (needed.Length > 0)
                {
                    conditions.Add(($"(_why = _jsynth_package_problem({string.Join(", ", needed)})) !== nothing", $"_jsynth_skip({id}, _why)"));
                }

                // The files say which file the loop is at, rather than showing the file.
                // An Only when node passes its value, or holds back the nodes after it.
                string compute = node == root || twins.Contains(node)
                    ?$"try\n{Indent}global {variable} = {expression}\n{Indent}_jsynth_frame({id}, _n, _path, {variable})\ncatch e\n{Indent}_jsynth_error({id}, e)\nend\n"
                    : node is WhenNode
                        ? $"try\n{Indent}if {condition}\n{Indent}{Indent}global {variable} = {expression}\n{Indent}{Indent}_jsynth_ok({id}, {variable})\n{Indent}else\n{Indent}{Indent}_jsynth_hold({id})\n"
                            + (inStream ? $"{Indent}{Indent}{kept}\n" :$"{Indent}{Indent}_jsynth_report({id}, \"skipped\", \"\", \"The condition is false: nothing passes.\")\n")
                            + $"{Indent}end\ncatch e\n{Indent}_jsynth_error({id}, e)\nend\n"
                    : Guarded(node.ID, $"global {variable} = {expression}", report: true, variable);

                if (conditions.Count == 0)
                {
                    return code.Append(compute).ToString();
                }

                for (int i = 0; i < conditions.Count; i++)
                {
                    _ = code.AppendLine($"{(i == 0 ? "if" : "elseif")} {conditions[i].Condition}").AppendLine($"{Indent}{conditions[i].Then}");
                }

                return code.AppendLine("else").Append(Indented(compute)).AppendLine("end").ToString();
            }

            // Plain newlines, whatever the platform or the line endings of this source file.
            return new JuliaScript(script.ToString().ReplaceLineEndings("\n"), variables, packages)
            {
                Streams = root is WatchNode,
                Watched = root as WatchNode,
                Looped = looped.Concat(carried.Select(c => c.ID)).ToHashSet(),
            };
        }

        /// <summary>
        /// A loop through files being generated: the node giving them, the folders zipped with it (their files of
        /// the same names go with its), the Zip node, and the nodes computed again for each.
        /// </summary>
        private sealed record LoopContext(FilesNode Root, List<FilesNode> Twins, ZipNode? Zip, HashSet<string> Nodes);

        /// <summary>
        /// The folders wired into <paramref name="zip"/>, in the order of its ports, or why they can't go in step.
        /// </summary>
        private static (List<FilesNode> Streams, string? Problem) ZipStreams(ZipNode zip, List<Connection> connections, Dictionary<string, Node> byID)
        {
            List<Node> wired = zip.Streams
                .Select(p => connections.FirstOrDefault(c => c.ParameterID == p.ID))
                .OfType<Connection>()
                .Select(c => byID[c.SourceID])
                .ToList();
            List<FilesNode> streams = wired.OfType<FilesNode>().ToList();
            string? problem = wired.Count < 2 ? "Wire in two folders or more, to go through their files in step."
                : streams.Count < wired.Count ? "Only folders go in step: wire in Files nodes or Watch folders."
                : streams.FirstOrDefault(f => !f.EachFile) is FilesNode all ? $"Set {all.FolderName} to go through its files one at a time."
                : streams.Any(f => f.Error is not null) ? "A folder wired in has a problem: see its node."
                : streams.Distinct().Count() < streams.Count ? "A folder is wired in twice."
                : null;
            return (streams, problem);
        }

        /// <summary>
        /// The ids of <paramref name="root"/> and every node its value reaches, through value wires (a
        /// function wired into a function port is applied, not given a value).
        /// </summary>
        private static HashSet<string> Downstream(Node root, List<Connection> connections, Dictionary<string, Node> byID)
        {
            HashSet<string> reached = [root.ID];
            Queue<string> pending = new([root.ID]);
            while (pending.TryDequeue(out string? id))
            {
                foreach (Connection wire in connections.Where(c => c.SourceID == id))
                {
                    bool value = byID[wire.TargetID].Inputs.Any(p => p.ID == wire.ParameterID && !p.IsFunctionPort);
                    if (value && reached.Add(wire.TargetID))
                    {
                        pending.Enqueue(wire.TargetID);
                    }
                }
            }

            return reached;
        }

        /// <summary>
        /// Julia code computing <paramref name="node"/>'s value from its wired inputs, or why it can't be computed.
        /// </summary>
        private static (string? Expression, string? Problem) Expression(Node node, List<Connection> inputs, Dictionary<string, string> variables, Dictionary<string, Node> byID, bool instrumented, string plotFolder, LoopContext? loop)
        {
            string? Input(Parameter parameter) => inputs.FirstOrDefault(c => c.ParameterID == parameter.ID) is Connection c ? variables[c.SourceID] : null;

            switch (node)
            {
                case Float x:
                    return ($"{x.OutputType}({FloatLiteral(x.Value)})", null);
                case Integer z:
                    return ($"{z.OutputType}({z.Value.ToString(CultureInfo.InvariantCulture)})", null);
                case UnsignedInteger n:
                    return ($"{n.OutputType}({n.Value.ToString(CultureInfo.InvariantCulture)})", null);
                case ArrayInput array:
                    return array.Error is null ? (array.Julia, null) : (null, array.Error);
                case SparseInput sparse:
                    return sparse.Error is null ? (sparse.Julia, null) : (null, sparse.Error);
                case ArrayFile file:
                    return file.Error is null ? (file.Julia, null) : (null, file.Error);
                case FilesNode files when loop?.Root == files:
                    // The file the loop is at, read as each of the folder's files is.
                    return (files.FrameJulia("_path"), null);
                case FilesNode files when loop?.Twins.Contains(files) == true:
                    // Zipped: its file of the name the loop is at.
                    return (files.FrameJulia($"joinpath({ArrayFile.PathLiteral(files.Folder)}, basename(_path))"), null);
                case ZipNode zip:
                {
                    (List<FilesNode> streams, string? problem) = ZipStreams(zip, inputs, byID);
                    return problem is not null ? (null, problem)
                        : loop?.Zip != zip ? (null, "Only one set of folders goes in step in a design: this one doesn't.")
                        : ($"collect(({string.Join(", ", streams.Select(s => variables[s.ID]))},))", null);
                }
                case FilesNode files when files.EachFile:
                    return (null, files.Error ?? (files is WatchNode
                        ? "Only one folder is gone through file by file in a design: this one isn't."
                        : "Only one folder is gone through file by file in a design, and a watched one comes first: this one isn't."));
                case FilesNode files:
                    return files.Error is null ? (files.Julia, null) : (null, files.Error);
                case FileNameNode name:
                    return loop is not null
                        ? (name.Julia, null)
                        : (null, "There's a file name only while files are gone through one at a time.");
                case WindowNode window:
                    return Input(window.Value) is string kept
                        ? (window.Julia($"{variables[window.ID]}_values", kept), null)
                        : (null, "Wire in the values to keep.");
                case WhenNode only:
                    return Input(only.Value) is string passed && Input(only.Condition) is not null
                        ? (passed, null)
                        : (null, "Wire in a value, and the condition on which it passes.");
                case MapNode map:
                {
                    if (Input(map.Items) is not string items)
                    {
                        return (null, "Wire values in to go through them.");
                    }

                    // The function itself, by name: Map calls it, once per value.
                    if (inputs.FirstOrDefault(c => c.ParameterID == map.Apply.ID) is not Connection wire || byID[wire.SourceID] is not Function function)
                    {
                        return (null, "Wire in the function to apply to each value.");
                    }

                    return MapNode.Problem(function) is string problem
                        ? (null, problem)
                        : (instrumented ? $"_jsynth_map({function.Name}, {items}{(map.InParallel ? "; parallel = true" : string.Empty)})"
                            : $"{(map.InParallel ? "_jsynth_tmap" : "map")}({function.Name}, {items})", null);
                }
                case ArrayBuilder builder:
                {
                    if (builder.Error is not null)
                    {
                        return (null, builder.Error);
                    }

                    // The builder's code names its wired arguments (m, n, ...); bind them to the inputs.
                    List<string> bindings = builder.Parameters.Where(p => Input(p) is not null).Select(p => $"{p.Name} = {Input(p)}").ToList();
                    return (bindings.Count == 0 ? builder.Julia : $"let {string.Join(", ", bindings)}\n{Indent}{builder.Julia}\nend", null);
                }

                case Function function:
                {
                    if (function.Error is not null)
                    {
                        return (null, function.Error);
                    }

                    if (function.Parameters.FirstOrDefault(p => Input(p) is null) is Parameter unwired)
                    {
                        return (null, $"Parameter {unwired.Name} isn't wired.");
                    }

                    return ($"{function.Name}({string.Join(", ", function.Parameters.Select(Input))})", null);
                }

                case PlotNode plot:
                    return Input(plot.Y) is string y
                        // In a loop, a file of its own each time it is drawn: the app may still be reading the last.
                        ? (loop is not null
                            ? plot.JuliaAt($"joinpath({ArrayFile.PathLiteral(plotFolder)}, \"{plot.ID}-$(_n).jsplot\")", y, Input(plot.X))
                            : plot.Julia(Path.Combine(plotFolder, $"{plot.ID}.jsplot"), y, Input(plot.X)), null)
                        : (null, "Wire values in to plot them.");

                case OutputNode output:
                {
                    if (output.Problem is string problem)
                    {
                        return (null, problem);
                    }

                    return Input(output.Input) is string value
                        ? (output is SaveFile { SavesPerFile: true } rows ? rows.JuliaPerFile(value, named: loop is not null) : output.Julia(value), null)
                        : (null, output is DisplayNode ? "Wire a value in to show it." : "Wire a value in to save it.");
                }

                default:
                    return (null, "This node can't be computed.");
            }
        }

        /// <summary>
        /// How to draw a plot in Julia, as a comment: JuliaSynth draws its plots itself.
        /// </summary>
        private static string PlotHint(PlotNode plot, List<Connection> inputs, Dictionary<string, string> variables)
        {
            string Wired(Parameter parameter) => variables[inputs.First(c => c.ParameterID == parameter.ID).SourceID];

            string y = Wired(plot.Y);
            string call = plot.X.IsWired ? $"plot({Wired(plot.X)}, {y})" : $"plot({y})";
            return $"# Plotted by JuliaSynth. With Plots.jl: using Plots; {call}";
        }

        /// <summary>
        /// A function's definition for running: evaluated on its own, after checking its packages loaded.
        /// </summary>
        private static string Definition(Function function)
        {
            string id = StringLiteral(function.ID);
            string define = Guarded(function.ID, $"include_string(@__MODULE__, {StringLiteral(function.Code)}, {StringLiteral(function.Name)})", report: false);
            if (function.RequiredPackages.Count == 0)
            {
                return define;
            }

            // Skipping the definition skips the calls too, with the reason on the node.
            string needed = string.Join(", ", function.RequiredPackages.Select(StringLiteral));
            return $"if (_why = _jsynth_package_problem({needed})) !== nothing\n{Indent}_jsynth_skip({id}, _why)\nelse\n{Indented(define)}end\n";
        }

        /// <summary>
        /// Every package <paramref name="node"/> can't do without: those loaded for it and, for a
        /// function, those its own code loads.
        /// </summary>
        private static IEnumerable<string> NeededPackages(Node node)
        {
            IEnumerable<string> packages = PackagesOf(node).Concat(ImportsOf(node));
            return node is Function function ? packages.Concat(function.RequiredPackages).Distinct() : packages;
        }

        /// <summary>
        /// The packages loaded with <c>using</c> for <paramref name="node"/>, before any function is defined.
        /// </summary>
        private static IEnumerable<string> PackagesOf(Node node)
        {
            IEnumerable<string> packages = node switch
            {
                ArrayBuilder builder => builder.Package is string package ? [package] : [],
                ArrayFile file => file.Package.Split(',', StringSplitOptions.TrimEntries),
                FilesNode files => files.Package.Split(',', StringSplitOptions.TrimEntries),
                SparseInput => ["SparseArrays"],
                OutputNode output => output.Packages,

                // A signature naming a sparse type needs SparseArrays to be defined at all.
                Function function => function.Parameters.Select(p => p.Shape).Append(function.ReturnShape).Any(JuliaTypes.IsSparse) ? ["SparseArrays"] : [],
                _ => [],
            };
            return packages;
        }

        /// <summary>
        /// The packages loaded with <c>import</c> for <paramref name="node"/>: used by qualified names only.
        /// </summary>
        private static IEnumerable<string> ImportsOf(Node node)
        {
            return node switch
            {
                ArrayFile file => FileFormats.Imports(file.Format),
                FilesNode files => FileFormats.Imports(files.Format),
                SaveFile { Format: FileFormats.Png } => ["ColorTypes"],
                _ => [],
            };
        }

        /// <summary>
        /// Loads each package on its own, so one that isn't installed only affects the nodes needing it:
        /// <paramref name="usings"/> with <c>using</c>, <paramref name="imports"/> with <c>import</c>
        /// (their functions say with <c>using</c> or <c>import</c> what to take from them).
        /// </summary>
        private static string LoadPackages(IEnumerable<string> usings, IEnumerable<string> imports)
        {
            IEnumerable<string> loads = usings.Select(p => $"({StringLiteral(p)}, \"using\")")
                .Concat(imports.Select(p => $"({StringLiteral(p)}, \"import\")"));

            return $$"""
                const _jsynth_missing = Dict{String, String}()
                for (_p, _how) in ({{string.Join(", ", loads)}},)
                    try
                        Core.eval(@__MODULE__, Meta.parse("$_how $_p"))
                    catch e
                        _jsynth_missing[_p] = sprint(showerror, e)
                    end
                end
                function _jsynth_package_problem(names...)
                    for n in names
                        haskey(_jsynth_missing, n) && return "Package $n can't be loaded. Install it with: import Pkg; Pkg.add(\"$n\")"
                    end
                    nothing
                end

                """;
        }

        /// <summary>
        /// <paramref name="code"/> in a try block reporting an error on the node, and the value when
        /// <paramref name="report"/> is set.
        /// </summary>
        private static string Guarded(string id, string code, bool report, string? variable = null)
        {
            StringBuilder block = new();
            _ = block.AppendLine("try").Append(Indented(code));
            if (report)
            {
                _ = block.AppendLine($"{Indent}_jsynth_ok({StringLiteral(id)}, {variable})");
            }

            return block.AppendLine("catch e").AppendLine($"{Indent}_jsynth_error({StringLiteral(id)}, e)").AppendLine("end").ToString();
        }

        private static string Indented(string code)
        {
            return string.Concat(code.TrimEnd('\n').Split('\n').Select(line => line.Length == 0 ? "\n" : $"{Indent}{line}\n"));
        }

        /// <summary>
        /// Every node's variable: x1, z1, v1, A1, ... by kind, f_out for a function f.
        /// </summary>
        private static Dictionary<string, string> NameVariables(List<Node> nodes)
        {
            HashSet<string> taken = nodes.OfType<Function>().Select(f => f.Name).ToHashSet();
            Dictionary<string, string> variables = [];
            foreach (Node node in nodes)
            {
                string stem = node switch
                {
                    Float => "x",
                    Integer => "z",
                    UnsignedInteger => "n",
                    VectorNode => "v",
                    MatrixNode => "A",
                    SparseInput => "S",
                    ArrayBuilder => "B",
                    ArrayFile => "D",
                    WindowNode => "window",
                    WhenNode => "passed",
                    FileNameNode => "name",
                    ZipNode => "zipped",
                    FilesNode { EachFile: true } => "frame",
                    FilesNode => "files",
                    MapNode => "mapped",
                    DisplayNode => "shown",
                    PlotNode => "plot",
                    SaveFile => "saved",
                    Function f => $"{f.Name}_out",
                    _ => "value",
                };

                string name = node is Function && !taken.Contains(stem) ? stem : Enumerable.Range(1, int.MaxValue).Select(i => $"{stem}{i}").First(n => !taken.Contains(n));
                _ = taken.Add(name);
                variables[node.ID] = name;
            }

            return variables;
        }

        /// <summary>
        /// The nodes with every node after the ones wired into it; otherwise in design order.
        /// </summary>
        private static List<Node> WiringOrder(List<Node> nodes, List<Connection> connections)
        {
            List<Node> order = [];
            HashSet<string> done = [];
            ILookup<string, string> inputs = connections.ToLookup(c => c.TargetID, c => c.SourceID);

            while (order.Count < nodes.Count)
            {
                // The wiring rules keep out loops; should one get in anyway, take the rest as they are.
                Node next = nodes.FirstOrDefault(n => !done.Contains(n.ID) && inputs[n.ID].All(done.Contains))
                    ?? nodes.First(n => !done.Contains(n.ID));
                order.Add(next);
                _ = done.Add(next.ID);
            }

            return order;
        }

        private static string FloatLiteral(double value)
        {
            return double.IsNaN(value) ? "NaN"
                : double.IsPositiveInfinity(value) ? "Inf"
                : double.IsNegativeInfinity(value) ? "-Inf"
                : value.ToString("R", CultureInfo.InvariantCulture);
        }

        /// <summary>
        /// A Julia string literal holding <paramref name="text"/> exactly.
        /// </summary>
        public static string StringLiteral(string text)
        {
            StringBuilder literal = new("\"");
            foreach (char c in text)
            {
                _ = literal.Append(c switch
                {
                    '\\' => "\\\\",
                    '"' => "\\\"",
                    '$' => "\\$",
                    '\n' => "\\n",
                    '\r' => string.Empty,
                    '\t' => "\\t",
                    _ => c.ToString(),
                });
            }

            return literal.Append('"').ToString();
        }
    }
