using JuliaSynth.Runtime;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace JuliaSynth.Model
{
    public static partial class ScriptGenerator
    {
        /// <summary>
        /// Writes one design's script: the preludes and packages it needs, its functions, the values worked out once,
        /// then the loop through files, if it has one.
        /// </summary>
        private sealed class Writer
        {
            private readonly bool _instrumented;
            private readonly string _plotFolder;
            private readonly string? _stopFile;
            private readonly List<Node> _nodes;
            private readonly List<Node> _order;
            private readonly List<Connection> _connections;
            private readonly List<Connection> _nextWires;
            private readonly Dictionary<string, Node> _byID;
            private readonly Dictionary<string, string> _variables;
            private readonly HashSet<string> _applied;
            private readonly LoopPlan _loop;
            private readonly StringBuilder _script = new();

            public Writer(IEnumerable<Node> designNodes, IEnumerable<Connection> designConnections, bool instrumented, string plotFolder, string? stopFile)
            {
                (_instrumented, _plotFolder, _stopFile) = (instrumented, plotFolder, stopFile);
                // Frames are comments on the canvas: nothing to work out.
                _nodes = designNodes.Where(n => n is not FrameNode).ToList();
                List<Connection> attached = designConnections.Where(c => Wiring.IsAttached(_nodes, c)).ToList();

                // Builders write wired arguments by name and typed-in ones by value; make sure they know which is
                // which for these connections (the designer keeps this up to date, a design built elsewhere may not).
                HashSet<string> wired = attached.Select(c => c.ParameterID).ToHashSet();
                foreach (Parameter parameter in _nodes.SelectMany(n => n.Ports))
                {
                    parameter.IsWired = wired.Contains(parameter.ID);
                }

                // Wires into next ports carry a value on to the next file: nothing waits for them.
                _nextWires = attached.Where(c => Wiring.IsNextWire(_nodes, c)).ToList();
                _connections = attached.Except(_nextWires).ToList();

                _variables = NameVariables(_nodes);
                _order = WiringOrder(_nodes, _connections);
                _byID = _nodes.ToDictionary(n => n.ID);

                // Functions wired into a Map are applied by it: one whose parameter isn't wired has no value of its own.
                _applied = _connections
                    .Where(c => _byID[c.TargetID].Inputs.Any(p => p.ID == c.ParameterID && p.IsFunctionPort))
                    .Select(c => c.SourceID)
                    .ToHashSet();
                _loop = LoopPlan.Of(_order, _connections, _nextWires, _byID);
            }

            public JuliaScript Write()
            {
                _ = _script.AppendLine("# Generated by JuliaSynth.");
                WritePreludes();
                List<string> packages = WritePackages();
                WriteFunctions();
                WriteValues();
                WriteLoop();

                // Plain newlines, whatever the platform or the line endings of this source file.
                return new JuliaScript(_script.ToString().ReplaceLineEndings("\n"), _variables, packages)
                {
                    Watched = _loop.Root as WatchNode,
                    Looped = _loop.Looped.Concat(_loop.Carried.Select(c => c.ID)).ToHashSet(),
                };
            }

            /// <summary>
            /// The Julia code the nodes' values are worked out with, as the design's nodes need it.
            /// </summary>
            private void WritePreludes()
            {
                if (_instrumented)
                {
                    _ = _script.AppendLine().AppendLine(Reports.Prelude.TrimEnd());
                    if (_nodes.OfType<PlotNode>().Any())
                    {
                        _ = _script.AppendLine(PlotData.Prelude.TrimEnd());
                    }
                }

                // Files go through Map; a script without them is still valid Julia, so these are in an exported one too.
                if (_nodes.Any(n => n is FilesNode or MapNode))
                {
                    _ = _script.AppendLine().AppendLine(FilesNode.Prelude.TrimEnd());
                }

                if (_instrumented && _nodes.OfType<MapNode>().Any())
                {
                    _ = _script.AppendLine(MapNode.Prelude.TrimEnd());
                }
                else if (_nodes.OfType<MapNode>().Any(m => m.InParallel))
                {
                    _ = _script.AppendLine(MapNode.ParallelPrelude.TrimEnd());
                }

                // Watching a folder is plain Julia too; showing how far a loop through files got is for runs.
                if (_nodes.OfType<WatchNode>().Any())
                {
                    _ = _script.AppendLine().AppendLine(WatchNode.Prelude.TrimEnd());
                }

                if (_instrumented && _nodes.OfType<FilesNode>().Any(f => f.EachFile))
                {
                    _ = _script.AppendLine(WatchNode.RunPrelude.TrimEnd());
                }

                if (_nodes.OfType<WindowNode>().Any())
                {
                    _ = _script.AppendLine().AppendLine(WindowNode.Prelude.TrimEnd());
                }

                if (_nodes.Any(n => n is ArrayFile file ? FileFormats.IsDelimited(file.Format) : n is FilesNode files && FileFormats.IsDelimited(files.Format)))
                {
                    _ = _script.AppendLine().AppendLine(FileFormats.Prelude.TrimEnd());
                }
            }

            /// <summary>
            /// Loads the packages: functions bring theirs into scope themselves (their code starts with its using
            /// statements); the rest come from here. A run checks them all first. Gives every package needed.
            /// </summary>
            private List<string> WritePackages()
            {
                List<string> usings = _order.SelectMany(PackagesOf).Distinct().Order(StringComparer.Ordinal).ToList();
                List<string> packages = _order.SelectMany(NeededPackages).Distinct().Order(StringComparer.Ordinal).ToList();
                if (_instrumented && packages.Count > 0)
                {
                    _ = _script.AppendLine().Append(LoadPackages(usings, packages.Except(usings)));
                    return packages;
                }

                List<string> imports = _order.SelectMany(ImportsOf).Distinct().Order(StringComparer.Ordinal).Except(usings).ToList();
                if (usings.Count + imports.Count > 0)
                {
                    _ = _script.AppendLine();
                }

                if (usings.Count > 0)
                {
                    _ = _script.AppendLine($"using {string.Join(", ", usings)}");
                }

                if (imports.Count > 0)
                {
                    _ = _script.AppendLine($"import {string.Join(", ", imports)}");
                }

                return packages;
            }

            private void WriteFunctions()
            {
                List<Function> functions = _order.OfType<Function>().Where(f => f.Error is null).ToList();
                if (functions.Count > 0)
                {
                    // Each definition is evaluated on its own, so a syntax error in one body only fails that function.
                    _ = _script.AppendLine().AppendLine("# Functions");
                    _ = _instrumented
                        ? _script.AppendJoin(string.Empty, functions.Select(Definition))
                        : _script.AppendJoin("\n\n", functions.Select(f => f.Code)).AppendLine();
                }
            }

            /// <summary>
            /// What keeps from value to value (the values a Window keeps, and files of rows started anew), then the
            /// values worked out once.
            /// </summary>
            private void WriteValues()
            {
                if (_order.Count > 0)
                {
                    _ = _script.AppendLine().AppendLine("# Values");
                }

                foreach (Node node in _order)
                {
                    if (node is WindowNode)
                    {
                        _ = _script.AppendLine($"{_variables[node.ID]}_values = []");
                    }
                    else if (node is SaveFile { SavesPerFile: true, Problem: null } rows)
                    {
                        _ = _script.AppendLine(rows.StartPerFile);
                    }
                }

                foreach (Node node in _order.Where(n => !_loop.Looped.Contains(n.ID)))
                {
                    _ = _script.Append(NodeCode(node));
                }
            }

            private void WriteLoop()
            {
                if (_loop.Root is not FilesNode root)
                {
                    // Without files to go through one at a time, there is no next file to take a value for.
                    if (_nextWires.Count > 0)
                    {
                        _ = _script.AppendLine().AppendLine(string.Join("\n", _nextWires.Select(c =>
                            $"# {_variables[c.TargetID]} keeps its value: it takes {ValueOf(_variables, c)} for the next file only when files are gone through one at a time.")));
                    }

                    return;
                }

                List<FilesNode> merged = _loop.Merged;

                // Merged, which folder the file is in: the folder numbered as the merge's ports.
                string body = (merged.Count > 0 ? $"_stream = _jsynth_stream(_path, {FilesNode.FoldersJulia(merged.Select(m => m.Folder))})\n" : string.Empty)
                    + string.Concat(_order.Where(n => _loop.Looped.Contains(n.ID)).Select(NodeCode)) + Reassignments();
                string frame = _variables[root.ID];
                List<string> inStep = _loop.Twins.Select(t => t.Folder).ToList();
                string files = inStep.Count > 0 ? $"_jsynth_in_step({root.Julia}, {FilesNode.FoldersJulia(inStep)})"
                    : merged.Count > 0 ? $"_jsynth_merged([{string.Join(", ", merged.Select(m => m.Julia))}])"
                    : root.Julia;
                string start = root is WatchNode watched
                    ? $"{watched.Watch(_instrumented ? _stopFile : null, inStep, merged.Where(m => m != root).ToList())} do _path, _n, _show"
                    : _instrumented
                        ? $"_jsynth_each({StringLiteral(root.ID)}, () -> {files}) do _path, _n, _show"
                        : $"for _path in {files}.paths";
                string until = _instrumented ? "until stopped" : "until stopped (Ctrl+C)";
                string what = root is WatchNode ? $"again for every file written to the folder, {until}" : "again for each file of the folder, in name order";
                if (inStep.Count > 0)
                {
                    what += $", with the files of the same name in {string.Join(", ", _loop.Twins.Select(t => _variables[t.ID]))}";
                }
                else if (merged.Count > 0)
                {
                    string folders = string.Join(", ", merged.Select(m => _variables[m.ID]));
                    what = root is WatchNode ? $"again for every file written to the folders of {folders}, {until}" : $"again for each file of the folders of {folders}, in name order";
                    frame = _variables[_loop.Streams!.ID];
                }

                _ = _script.AppendLine().AppendLine($"# The loop: the values from {frame} on, {what}");
                if (_instrumented)
                {
                    _ = _script.AppendLine("const _jsynth_before_loop = copy(_jsynth_failed)")
                        .AppendLine("const _jsynth_held_before_loop = copy(_jsynth_held)")
                        .AppendLine(start)
                        .AppendLine($"{Indent}_jsynth_frame_start(_show, _jsynth_before_loop, _jsynth_held_before_loop)")
                        .Append(Indented(body))
                        .AppendLine("end")
                        .AppendLine("_jsynth_quiet[] = false");
                }
                else
                {
                    _ = _script.AppendLine(start).Append(Indented(body)).AppendLine("end");
                }
            }

            /// <summary>
            /// After each file, the inputs with a next value take it, all together: the values they get are those of
            /// this file. In a run, an input whose next value failed keeps the one it has.
            /// </summary>
            private string Reassignments()
            {
                if (_nextWires.Count == 0)
                {
                    return string.Empty;
                }

                // An input taking another's value takes the one it had for this file: through a temporary.
                bool chained = _nextWires.Any(w => _loop.Carried.Any(c => c.ID == w.SourceID));
                StringBuilder code = new("# The inputs take their next values, for the next file\n");
                List<(Connection Wire, string Value)> values = [];
                for (int i = 0; i < _nextWires.Count; i++)
                {
                    Connection wire = _nextWires[i];
                    string next = ValueOf(_variables, wire);
                    if (chained)
                    {
                        string input = _variables[wire.TargetID];
                        _ = code.AppendLine(_instrumented
                            ? $"_next{i + 1} = _jsynth_blocked({StringLiteral(wire.SourceID)}) ? {input} : {next}"
                            : GateOf(wire.SourceID) is string held ? $"_next{i + 1} = {held} ? {next} : {input}"
                            : $"_next{i + 1} = {next}");
                        next = $"_next{i + 1}";
                    }

                    values.Add((wire, next));
                }

                foreach ((Connection wire, string next) in values)
                {
                    string input = _variables[wire.TargetID];
                    _ = !_instrumented ? code.Append(Gated(GateOf(wire.SourceID), $"global {input} = {next}"))
                        : chained ? code.AppendLine($"global {input} = {next}").AppendLine($"_jsynth_ok({StringLiteral(wire.TargetID)}, {input})")
                        : code.AppendLine($"_jsynth_blocked({StringLiteral(wire.SourceID)}) || (global {input} = {next})").AppendLine($"_jsynth_ok({StringLiteral(wire.TargetID)}, {input})");
                }

                return code.ToString();
            }

            /// <summary>
            /// In a plain script, whether the Only when nodes before a node let its value through, and the folders
            /// merged before it have a file: <c>passed1_ok &amp;&amp; @isdefined(frame2)</c>; null when nothing holds it.
            /// </summary>
            private string? GateOf(string id, bool self = true)
            {
                IEnumerable<Node> whens = _loop.Gates.TryGetValue(id, out List<Node>? before) ? before : [];
                if (self && _byID[id] is WhenNode when)
                {
                    whens = whens.Append(when);
                }

                List<string> flags = whens.Select(w => w is WhenNode ? $"{_variables[w.ID]}_ok" : $"@isdefined({_variables[w.ID]})").ToList();
                return flags.Count == 0 ? null : string.Join(" && ", flags);
            }

            private static string Gated(string? gate, string code)
            {
                code = code.EndsWith('\n') ? code : code + "\n";
                return gate is null ? code : $"if {gate}\n{Indented(code)}end\n";
            }

            /// <summary>
            /// What a node's code is made of: its wired inputs, its variable, whether it is in the loop, its value's
            /// expression or why it has none, and the lines giving its other outputs: a merge's folder, a folder's file name
            /// and path.
            /// </summary>
            private sealed record NodeParts(Node Node, List<Connection> Inputs, string Variable, bool InLoop, string? Expression, string? Problem, string Outputs);

            /// <summary>
            /// One node's value: computed (and reported, in a run), or why it isn't.
            /// </summary>
            private string NodeCode(Node node)
            {
                List<Connection> inputs = _connections.Where(c => c.TargetID == node.ID).ToList();
                if (node is Function used && _applied.Contains(used.ID) && used.Parameters.Any(p => inputs.All(c => c.ParameterID != p.ID)))
                {
                    return string.Empty;
                }

                string variable = _variables[node.ID];
                bool inLoop = _loop.Looped.Contains(node.ID);
                (string? expression, string? problem) = Expression(node, inputs, _variables, _byID, _instrumented, _plotFolder, inLoop ? _loop : null);

                NodeParts parts = new(node, inputs, variable, inLoop, expression, problem, problem is null ? OtherOutputs(node, variable, inLoop) : string.Empty);
                return _instrumented ? RunCode(parts) : PlainCode(parts);
            }

            /// <summary>
            /// The lines giving a node's outputs other than its value: a merge's folder (the name of the folder the file
            /// is in), and a folder's file name and path, those wired (the file its value is read from).
            /// </summary>
            private string OtherOutputs(Node node, string variable, bool inLoop)
            {
                if (node == _loop.Streams && node is MergeNode)
                {
                    return $"{(inLoop ? "global " : string.Empty)}{variable}_{MergeNode.FolderOutput} = ({string.Join(", ", _loop.Merged.Select(m => StringLiteral(m.FolderName)))},)[_stream]\n";
                }

                if (node is not FilesNode folder || !_loop.ReadsFrame(node))
                {
                    return string.Empty;
                }

                bool Wired(string output) => _connections.Concat(_nextWires).Any(c => c.SourceID == node.ID && c.Output == output);
                string path = _loop.PathOf(folder);
                return (Wired(FilesNode.NameOutput) ? $"global {variable}_{FilesNode.NameOutput} = basename({path})\n" : string.Empty)
                    + (Wired(FilesNode.PathOutput) ? $"global {variable}_{FilesNode.PathOutput} = abspath({path})\n" : string.Empty);
            }

            /// <summary>
            /// An Only when node's condition, which says whether its value passes.
            /// </summary>
            private string? ConditionOf(NodeParts parts) => parts.Node is WhenNode gate && parts.Inputs.FirstOrDefault(c => c.ParameterID == gate.Condition.ID) is Connection test
                ? ValueOf(_variables, test)
                : null;

            /// <summary>
            /// A node's value in a plain script. Showing or saving a value is something to do, not a value to keep;
            /// plots are drawn by JuliaSynth, so a plain script only says how to draw them in Julia. A node after an
            /// Only when node is worked out only when its condition held.
            /// </summary>
            private string PlainCode(NodeParts parts)
            {
                (Node node, List<Connection> inputs, string variable, bool inLoop, string? expression, string? problem, string outputs) = parts;

                // Values of a loop are assigned in a function (the one called for each file) or a loop: globals, by name.
                string assign = inLoop ? $"global {variable}" : variable;
                string line = problem is not null ? $"# {variable}: {problem}"
                    : node is SaveFile { SavesPerFile: true } rows ? rows.PerFileStatement(ValueOf(_variables, inputs[0]), named: inLoop)
                    : node is OutputNode output ? output.Statement(ValueOf(_variables, inputs[0]))
                    : node is PlotNode plot ? PlotHint(plot, inputs, _variables)
                    : node is WhenNode ? $"{(inLoop ? "global " : string.Empty)}{variable}_ok = {ConditionOf(parts)}\nif {variable}_ok\n{Indent}{assign} = {expression}\nend"
                    : $"{outputs}{assign} = {expression}";

                // A folder merged reads the file when it is in it, and keeps its latest otherwise.
                int stream = _loop.StreamOf(node);
                return problem is not null ? line + "\n"
                    : stream > 0 ? $"if _stream == {stream}\n{Indented(line)}end\n"
                    : Gated(GateOf(node.ID, self: false), line);
            }

            /// <summary>
            /// A node's value in a run: worked out unless something before it failed or holds it back, and reported.
            /// </summary>
            private string RunCode(NodeParts parts)
            {
                (Node node, List<Connection> inputs, string variable, bool inLoop, string? expression, string? problem, string outputs) = parts;
                StringBuilder code = new($"# {variable}\n");
                if (problem is not null)
                {
                    return code.AppendLine($"_jsynth_skip({StringLiteral(node.ID)}, {StringLiteral(problem)})").ToString();
                }

                string id = StringLiteral(node.ID);
                string[] blockers = inputs.Select(c => StringLiteral(c.SourceID)).Distinct().ToArray();
                string[] needed = NeededPackages(node).Select(StringLiteral).ToArray();
                List<(string Condition, string Then)> conditions = [];

                // Merged: a folder reads the file when it is in it, and otherwise keeps its latest, the nodes after it
                // waiting until its first. The merge gives the file of the folder it is in, failing when that did.
                int stream = _loop.StreamOf(node);
                if (stream > 0)
                {
                    conditions.Add(($"_stream != {stream}", $"@isdefined({variable}) || _jsynth_hold({id})"));
                }
                else if (_loop.IsMerge(node))
                {
                    conditions.Add(($"_jsynth_blocked(({string.Join(", ", _loop.Merged.Select(m => StringLiteral(m.ID)))},)[_stream])", $"_jsynth_skip({id}, \"The file failed to read.\")"));
                    blockers = [];
                }

                // A plot of a loop is drawn for the files whose values are shown, not for every one.
                if (inLoop && node is PlotNode)
                {
                    conditions.Add(("_jsynth_quiet[]", "nothing"));
                }

                // A function whose definition failed has nothing to call; its error is already reported.
                if (node is Function)
                {
                    conditions.Add(($"_jsynth_blocked({id})", "nothing"));
                }

                // Held back, it shows the value it keeps: on a file whose values are shown, the one it got may not have
                // been (a plot keeps showing its last drawing).
                string kept = node is PlotNode ? "nothing" : $"@isdefined({variable}) && _jsynth_ok({id}, {variable})";

                // Held back by a false condition before it, or a folder merged with no file yet: going through files,
                // it keeps the value it had.
                string[] holders = inputs.Where(c => node != _loop.Streams && (_byID[c.SourceID] is WhenNode || _loop.Merged.Any(m => m.ID == c.SourceID) || _loop.Gates.ContainsKey(c.SourceID)))
                    .Select(c => StringLiteral(c.SourceID))
                    .Distinct()
                    .ToArray();
                if (holders.Length > 0)
                {
                    conditions.Add(($"_jsynth_held_by({string.Join(", ", holders)})", inLoop
                        ? $"(_jsynth_hold({id}); {kept})"
                        : $"(_jsynth_hold({id}); _jsynth_skip({id}, \"A condition before it is false: nothing passed.\"))"));
                }

                if (blockers.Length > 0)
                {
                    conditions.Add(($"_jsynth_blocked({string.Join(", ", blockers)})", $"_jsynth_skip({id}, \"An input failed.\")"));
                }

                if (needed.Length > 0)
                {
                    conditions.Add(($"(_why = _jsynth_package_problem({string.Join(", ", needed)})) !== nothing", $"_jsynth_skip({id}, _why)"));
                }

                // The files say which file the loop is at, rather than showing the file.
                // An Only when node passes its value, or holds back the nodes after it.
                string compute = _loop.ReadsFrame(node)
                    ? $"try\n{(outputs.Length > 0 ? Indented(outputs) : string.Empty)}{Indent}global {variable} = {expression}\n{Indent}_jsynth_frame({id}, _n, _path, {variable})\ncatch e\n{Indent}_jsynth_error({id}, e)\nend\n"
                    : node is WhenNode
                        ? $"try\n{Indent}if {ConditionOf(parts)}\n{Indent}{Indent}global {variable} = {expression}\n{Indent}{Indent}_jsynth_ok({id}, {variable})\n{Indent}else\n{Indent}{Indent}_jsynth_hold({id})\n"
                            + (inLoop ? $"{Indent}{Indent}{kept}\n" : $"{Indent}{Indent}_jsynth_report({id}, \"skipped\", \"\", \"The condition is false: nothing passes.\")\n")
                            + $"{Indent}end\ncatch e\n{Indent}_jsynth_error({id}, e)\nend\n"
                    : Guarded(node.ID, $"{outputs}global {variable} = {expression}", report: true, variable);

                // Lit up while worked out, and timed.
                compute = $"_jsynth_start({id})\n{compute}";

                if (conditions.Count == 0)
                {
                    return code.Append(compute).ToString();
                }

                for (int i = 0; i < conditions.Count; i++)
                {
                    _ = code.AppendLine($"{(i == 0 ? "if" : "elseif")} {conditions[i].Condition}").AppendLine($"{Indent}{conditions[i].Then}");
                }

                return code.AppendLine("else").Append(Indented(compute)).AppendLine("end").ToString();
            }
        }
    }
